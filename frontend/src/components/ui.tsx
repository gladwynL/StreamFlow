import type { ReactNode } from 'react';

/** A headline measurement with its unit and provenance. Null renders as an em dash, never as zero. */
export function Metric({
  label,
  value,
  unit,
  hint,
  tone,
}: {
  label: string;
  value: string | null;
  unit?: string;
  /** Where the number comes from and over what window. */
  hint: string;
  tone?: 'ok' | 'warn' | 'bad';
}) {
  const toneClass =
    tone === 'bad'
      ? 'text-bad'
      : tone === 'warn'
        ? 'text-warn'
        : tone === 'ok'
          ? 'text-ok'
          : 'text-ink';
  return (
    <div className="rounded-xl border border-line bg-panel px-4 py-3.5">
      <p className="text-xs font-medium tracking-wide text-ink-muted uppercase">{label}</p>
      <p className={`tabular mt-1.5 font-mono text-2xl font-semibold ${toneClass}`}>
        {value ?? '—'}
        {value !== null && unit && (
          <span className="ml-1 text-sm font-normal text-ink-muted">{unit}</span>
        )}
      </p>
      <p className="mt-1 text-xs text-ink-faint">{hint}</p>
    </div>
  );
}

export function PageHeader({
  title,
  description,
  actions,
}: {
  title: string;
  description: ReactNode;
  actions?: ReactNode;
}) {
  return (
    <header className="flex flex-col gap-3 sm:flex-row sm:items-end sm:justify-between">
      <div>
        <h1 className="text-2xl font-semibold tracking-tight text-ink">{title}</h1>
        <p className="mt-1 max-w-3xl text-sm text-ink-muted">{description}</p>
      </div>
      {actions && <div className="flex flex-wrap items-center gap-2">{actions}</div>}
    </header>
  );
}

/** Marks traffic produced by the simulator. */
export function SyntheticBadge({ className = '' }: { className?: string }) {
  return (
    <span
      className={`inline-flex items-center gap-1 rounded border border-synthetic/40 bg-synthetic/10 px-1.5 py-0.5 text-[11px] font-medium text-synthetic ${className}`}
      title="Generated by the StreamFlow simulator; not real user activity"
    >
      Synthetic
    </span>
  );
}

export function LoadingState({ label = 'Loading…' }: { label?: string }) {
  return (
    <div
      role="status"
      className="flex items-center gap-3 rounded-xl border border-line bg-panel p-6"
    >
      <span aria-hidden="true" className="live-dot size-2 rounded-full bg-accent" />
      <span className="text-sm text-ink-muted">{label}</span>
    </div>
  );
}

export function EmptyState({ title, children }: { title: string; children?: ReactNode }) {
  return (
    <div className="rounded-xl border border-dashed border-line-strong px-6 py-10 text-center">
      <p className="text-sm font-medium text-ink">{title}</p>
      {children && <div className="mt-1 text-sm text-ink-muted">{children}</div>}
    </div>
  );
}

export function ErrorState({ message, onRetry }: { message: string; onRetry?: () => void }) {
  return (
    <div role="alert" className="rounded-xl border border-bad/40 bg-bad/10 p-5">
      <p className="text-sm font-semibold text-bad">Could not load this data</p>
      <p className="mt-1 text-sm text-ink-muted">{message}</p>
      {onRetry && (
        <button type="button" onClick={onRetry} className="btn-secondary mt-3">
          Try again
        </button>
      )}
    </div>
  );
}

export function Notice({ tone, children }: { tone: 'warn' | 'bad' | 'info'; children: ReactNode }) {
  const classes =
    tone === 'bad'
      ? 'border-bad/40 bg-bad/10 text-bad'
      : tone === 'warn'
        ? 'border-warn/40 bg-warn/10 text-warn'
        : 'border-accent/30 bg-accent/5 text-ink';
  return <div className={`rounded-lg border px-4 py-3 text-sm ${classes}`}>{children}</div>;
}

/** A horizontal proportion bar with an accessible label. */
export function Meter({ value, max, label }: { value: number; max: number; label: string }) {
  const percent = max > 0 ? Math.min(100, (value / max) * 100) : 0;
  return (
    <div
      role="meter"
      aria-label={label}
      aria-valuemin={0}
      aria-valuemax={max}
      aria-valuenow={value}
      className="h-2 w-full overflow-hidden rounded-full bg-panel-raised"
    >
      <div className="h-full rounded-full bg-accent" style={{ width: `${percent}%` }} />
    </div>
  );
}
